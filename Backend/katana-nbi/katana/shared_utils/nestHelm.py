"""Translate the supported NEST chart profile into OSM KDU parameters."""
import re


def free5gc_parameters(config):
    """SD-only profile for the adapted free5GC chart (SST 1, source SD 010203)."""
    fields = {"profile", "member_vnf_index", "kdu_name", "sd"}
    if not isinstance(config, dict) or set(config) != fields:
        raise ValueError("helm_configuration requires profile, member_vnf_index, kdu_name and sd only")
    if config["profile"] != "free5gc-sd-v1":
        raise ValueError("Unsupported Helm configuration profile")
    sd = config["sd"]
    if not isinstance(sd, str) or not re.fullmatch(r"[0-9a-fA-F]{6}", sd):
        raise ValueError('SD must be a quoted six-digit hexadecimal string, for example "000002"')
    if sd.lower() == "ffffff":
        raise ValueError("FFFFFF is reserved and cannot identify this slice")
    for field in ("member_vnf_index", "kdu_name"):
        if not isinstance(config[field], str) or not re.fullmatch(r"[A-Za-z0-9_.-]{1,128}", config[field]):
            raise ValueError(f"Invalid {field}")
    return [{
        "member-vnf-index": config["member_vnf_index"],
        "additionalParamsForKdu": [{
            "kdu_name": config["kdu_name"],
            "additionalParams": {"global": {"katanaNestSd": sd.lower()}},
        }],
    }]


def deployment_nest_parameters(nest, nsd_id, nfvo_id, clusters):
    """Single-service NEST for the existing Kubernetes deployment endpoint."""
    if not isinstance(nest, dict):
        raise ValueError("NEST must be an object")
    descriptor = nest.get("service_descriptor")
    services = descriptor.get("ns_list") if isinstance(descriptor, dict) else None
    if not isinstance(services, list) or len(services) != 1 or not isinstance(services[0], dict):
        raise ValueError("Kubernetes deployment requires exactly one NEST service")
    service = services[0]
    for key, selected in (("nsd-id", nsd_id), ("nfvo-id", nfvo_id)):
        if service.get(key) and service[key] != selected:
            raise ValueError(f"NEST {key} does not match the selected deployment")
    if (service.get("target") or service.get("placement")) and len(clusters) > 1:
        raise ValueError("Explicit NEST placement requires a VIM with one registered cluster")
    matching = clusters
    if service.get("target"):
        matching = [cluster for cluster in matching if cluster.get("id") == service["target"]]
        if not matching:
            raise ValueError("NEST target does not belong to the selected NFVO and VIM")
    if service.get("placement") and not any(cluster.get("location") == service["placement"] for cluster in matching):
        raise ValueError("NEST placement does not match the selected infrastructure")
    if "additionalParamsForVnf" in service:
        raise ValueError("Use helm_configuration; OSM parameters are generated by Katana")
    return free5gc_parameters(service.get("helm_configuration"))
